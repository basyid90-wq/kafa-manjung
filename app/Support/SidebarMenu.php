    /** @return array<int, array{title: string, items: array}> */
    public static function for(User $user): array
    {
        $meta      = self::routeMeta();
        $userRoles = $user->getRoleNames()->all();
        $type      = $user->school?->type ?? 'sekolah';
        $typePlans = config("plans.types.$type.plans", array_keys(config('plans.plans')));

        $groups = [];
        foreach (self::definition() as $title => $items) {
            $out = [];
            foreach ($items as $def) {
                [$name, $label, $icon, $active] = $def;
                if (!isset($meta[$name])) continue;

                // Every "role:" middleware on the route must pass (nested groups stack)
                $roleSets = isset($def[4]) ? [$def[4]] : $meta[$name]['roles'];
                foreach ($roleSets as $set) {
                    if (!array_intersect($set, $userRoles)) continue 2;
                }

                $module = $meta[$name]['module'];
                $locked = $module && !$user->canUse($module);
                $plan   = null;
                if ($locked) {
                    // Upsell the cheapest plan this workspace type can buy that includes the module;
                    // none (e.g. Sekolah-only module in a Personal workspace) → hide the item
                    $need = config('plans.plans.'.config("plans.modules.$module.plan").'.rank');
                    $plan = collect($typePlans)->first(fn ($p) => config("plans.plans.$p.rank") >= $need);
                    if (!$plan) continue;
                }

                $out[] = [
                    'label'     => $label,
                    'url'       => $locked ? route('subscription.index', ['modul' => $module]) : route($name),
                    'icon'      => self::ICONS[$icon],
                    'active'    => !$locked && request()->routeIs(...$active),
                    'locked'    => $locked,
                    'planLabel' => $locked ? config("plans.plans.$plan.label") : null,
                    'plan'      => $plan,
                ];
            }
            if ($out) $groups[] = ['title' => $title, 'items' => $out];
        }

        return $groups;
    }

    /** route name => [role sets from each "role:" middleware, module from "plan:" middleware] */
    private static function routeMeta(): array
    {
        static $meta = null;
        if ($meta !== null) return $meta;

        $meta = [];
        foreach (Route::getRoutes()->getRoutesByName() as $name => $route) {
            $roles = [];
            $module = null;
            foreach ($route->gatherMiddleware() as $mw) {
                if (!is_string($mw)) continue;
                if (str_starts_with($mw, 'role:')) $roles[] = explode('|', substr($mw, 5));
                if (str_starts_with($mw, 'plan:')) $module = substr($mw, 5);
            }
            $meta[$name] = ['roles' => $roles, 'module' => $module];
        }

        return $meta;
    }
